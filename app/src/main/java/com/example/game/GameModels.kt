package com.example.game

enum class GamePhase {
    LOADING,
    TITLE,
    PLAYING,
    PAUSED,
    GAMEOVER,
}

enum class ThemeId(val wireId: String) {
    SUBWAY_CLASSIC("subway-classic"),
    SUNSET_CITY("sunset-city"),
    NEON_METRO("neon-metro"),
}

enum class OutfitId(val wireId: String) {
    CYAN_STREET("cyan-street"),
    GOLD_RUSH("gold-rush"),
    CRIMSON_DASH("crimson-dash"),
}

enum class PowerupType {
    JETPACK,
    MAGNET,
    MULTIPLIER,
}

enum class BarrierKind {
    LOW,
    HIGH,
    TALL,
}

data class ThemePalette(
    val id: ThemeId,
    val name: String,
    val subtitle: String,
    val skyTop: Int,
    val skyHorizon: Int,
    val fogColor: Int,
    val fogDensity: Float,
    val sunColor: Int,
    val sunIntensity: Float,
    val hemiSky: Int,
    val hemiGround: Int,
    val hemiIntensity: Float,
    val trackBedHex: String,
    val platformColor: Int,
    val wallHex: String,
    val buildingColors: IntArray,
    val accentColor: Int,
    val hasBirds: Boolean,
    val isNight: Boolean,
)

data class OutfitConfig(
    val id: OutfitId,
    val name: String,
    val hoodieColor: Int,
    val teeColor: Int,
    val pantsColor: Int,
    val capPrimary: Int,
    val capSecondary: Int,
    val shoeColor: Int,
    val backpackColor: Int,
    val skinColor: Int,
    val hairColor: Int,
    val swatchColor: Long,
    val accentSwatchColor: Long,
)

data class HudSnapshot(
    val score: Int = 0,
    val coins: Int = 0,
    val distance: Int = 0,
    val speedMultiplier: Float = 1.0f,
    val scoreMultiplier: Int = 1,
    val jetpackTime: Float = 0f,
    val jetpackMaxTime: Float = 7.5f,
    val magnetTime: Float = 0f,
    val magnetMaxTime: Float = 9.0f,
    val multiplierTime: Float = 0f,
    val multiplierMaxTime: Float = 10.0f,
    val isFlying: Boolean = false,
    val policeProximity: Float = 0.85f,
    val headstartReady: Boolean = true,
    val bustReason: String = "",
)

